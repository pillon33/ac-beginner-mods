"""
gen_layout.py — generate pitwall_core/layout.py from the ctypes
structs in telemetry/shared_memory.py.

The ctypes structs are the single source of truth for AC's shared
memory layout. The in-game app can't use them (AC's Python has no
ctypes), so this script writes each field's byte offset and `struct`
format into a plain Python 3.3-compatible module instead. ctypes
works out the offsets, padding included, so nothing is computed by
hand.

Usage (Windows only, like shared_memory.py itself):
    python scripts/gen_layout.py           # rewrite pitwall_core/layout.py
    python scripts/gen_layout.py --check   # exit 1 if it's out of date

tests/test_layout.py runs the same check.
"""

import argparse
import ctypes
import os
import struct
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYOUT_PATH = os.path.join(REPO_ROOT, "pitwall_core", "layout.py")

sys.path.insert(0, os.path.join(REPO_ROOT, "telemetry"))

from shared_memory import BLOCKS  # noqa: E402

SCALAR_FORMATS = {
    ctypes.c_int32: "i",
    ctypes.c_float: "f",
}

HEADER = '''"""
layout.py — GENERATED by scripts/gen_layout.py from the ctypes structs
in telemetry/shared_memory.py. Do not edit: change the structs and run
`python scripts/gen_layout.py`.

For each shared memory block: its tag, how many bytes to map, and
field name -> (byte offset, little-endian `struct` format). A format
ending in "s" is a UTF-16 string (Kunos' wchar arrays).
"""
'''


def field_format(ctype):
    """The `struct` format that reads the same bytes as `ctype`."""
    if issubclass(ctype, ctypes.Array):
        element, length = ctype._type_, ctype._length_
        if element is ctypes.c_wchar:
            return "{}s".format(length * 2)
        if element in SCALAR_FORMATS:
            return "{}{}".format(length, SCALAR_FORMATS[element])
        raise ValueError("unsupported array element type: {!r}".format(element))
    if ctype in SCALAR_FORMATS:
        return SCALAR_FORMATS[ctype]
    raise ValueError("unsupported field type: {!r}".format(ctype))


def render():
    lines = [HEADER]
    for name, tag, struct_type in BLOCKS:
        prefix = name.upper()
        lines.append("")
        lines.append("{}_TAG = {!r}".format(prefix, tag))
        lines.append("{}_SIZE = {}".format(prefix, ctypes.sizeof(struct_type)))
        lines.append("{} = {{".format(prefix))
        for field_name, ctype in struct_type._fields_:
            offset = getattr(struct_type, field_name).offset
            fmt = field_format(ctype)
            if struct.calcsize("<" + fmt) != ctypes.sizeof(ctype):
                raise ValueError("{}.{}: format {!r} doesn't match ctypes size".format(
                    struct_type.__name__, field_name, fmt))
            lines.append("    {!r}: ({}, {!r}),".format(field_name, offset, fmt))
        lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="don't write; exit 1 if layout.py is out of date")
    args = parser.parse_args()

    expected = render()
    if args.check:
        with open(LAYOUT_PATH, encoding="utf-8") as current:
            if current.read() != expected:
                sys.exit("pitwall_core/layout.py is out of date: run python scripts/gen_layout.py")
        print("pitwall_core/layout.py is up to date")
        return

    with open(LAYOUT_PATH, "w", encoding="utf-8", newline="\n") as output:
        output.write(expected)
    print("Wrote {}".format(LAYOUT_PATH))


if __name__ == "__main__":
    main()
